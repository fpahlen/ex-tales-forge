defmodule TalesForge.Scenes do
  @moduledoc """
  Reads of the stored scenes (`TalesForge.Schemas.Scene`). A leaf: it
  depends on the schema and the Repo only, so the turn code (`Game.Context`)
  can read the opening scene without depending on `TalesForge.GameSessions`.
  """

  import Ecto.Query

  alias TalesForge.Repo
  alias TalesForge.Schemas.Scene

  @doc """
  The GM's opening narration: the session's first scene (generated by the scene
  job `TalesForge.GameSessions.create_session/1` enqueues), or nil until it
  exists. Players cannot act before it (`TalesForge.GameSessions.submit_message/3`
  returns `{:error, :needs_scene}`).
  """
  @spec opening(String.t()) :: Scene.t() | nil
  def opening(session_id) when is_binary(session_id) do
    Scene
    |> where([s], s.game_session_id == ^session_id)
    |> order_by(asc: :inserted_at)
    |> limit(1)
    |> Repo.one()
  end
end
